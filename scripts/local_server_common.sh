#!/usr/bin/env bash
# Prefer the sibling droneengage_server_common checkout over the git
# dependency: writes .cargo/config.toml (machine-local, gitignored) with a
# source replacement so `cargo build` compiles the local working tree.
# Without the sibling (or without this file) cargo fetches the git
# dependency from Cargo.toml instead.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
COMMON="$ROOT/../droneengage_server_common"
VEND="$ROOT/.cargo/vendor-local"

if [ ! -f "$COMMON/Cargo.toml" ]; then
  rm -f "$ROOT/.cargo/config.toml"
  rm -rf "$VEND"
  echo "no sibling droneengage_server_common - cargo will use the git dependency"
  exit 0
fi

# directory sources only see crate dirs carrying a checksum file, so the
# checkout is reached through a dedicated dir holding just this symlink
printf '{"files":{}}\n' > "$COMMON/.cargo-checksum.json"
mkdir -p "$VEND"
ln -sfn "$(cd "$COMMON" && pwd)" "$VEND/droneengage_server_common"
cat > "$ROOT/.cargo/config.toml" <<'EOCFG'
# generated by scripts/local_server_common.sh - do not commit; delete to
# go back to the git dependency in Cargo.toml
[source.prv-server-common]
git = "https://github.com/DroneEngage/droneengage_server_common"
branch = "master"
replace-with = "local-server-common"

[source.local-server-common]
directory = ".cargo/vendor-local"
EOCFG
echo "using local droneengage_server_common at $(cd "$COMMON" && pwd)"
